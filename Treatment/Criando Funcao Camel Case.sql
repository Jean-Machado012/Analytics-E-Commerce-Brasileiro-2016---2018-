CREATE FUNCTION  fn_camel_case( TEXTO VARCHAR(5000) )
RETURNS VARCHAR(5000)
DETERMINISTIC
BEGIN
	
    -- DECLARAÇÂO DAS VARIÁVEIS
    DECLARE POSICAO 		INT 		 DEFAULT 1;
    DECLARE V_CHAR	 		CHAR(1) 	 DEFAULT 1;
    DECLARE CHAR_ANTERIOR	CHAR(1) 	 DEFAULT 1;
    DECLARE NOME_FORMATADO	VARCHAR(100) DEFAULT LOWER( TEXTO );
    
    -- ENQUANTO A POSIÇÃO FOR MENOR QUE O TAMANHO DO TEXTO
    WHILE POSICAO <= CHAR_LENGTH( TEXTO ) DO
		
        -- ANALISA O TEXTO, NA POSICAO DO CARACTERE
        SET V_CHAR = SUBSTRING( TEXTO, POSICAO, 1);
        SET CHAR_ANTERIOR = 
			CASE
				WHEN POSICAO = 1 THEN ' '
                ELSE SUBSTRING( TEXTO, POSICAO -1, 1)
			END;
		
        IF CHAR_ANTERIOR IN (' ') THEN
			SET NOME_FORMATADO = INSERT( NOME_FORMATADO, POSICAO, 1, UPPER( V_CHAR ) );
		END IF;
            
		SET POSICAO = POSICAO + 1;
        
	END WHILE;

	RETURN NOME_FORMATADO;

END $$

